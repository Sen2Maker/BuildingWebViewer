#!/usr/bin/env python3
"""Bundle source modules and package an offline-ready static site; no npm dependencies."""
from pathlib import Path
import argparse
import hashlib
import html
import json
import re
import shutil
import zipfile

HERE = Path(__file__).resolve().parent
PAGES = ('index.html', 'lod.html', 'wireframe.html', 'pointcloud.html')
ICONS = ('favicon.svg', 'favicon.ico', 'favicon-32.png', 'apple-touch-icon.png')
ENTRIES = {'mobile': 'src/mobile/home.js', 'hub': 'src/hub/hub.js', 'lod': 'src/lod/app.js', 'cloud': 'src/cloud/cloud-app.js'}
IMPORT = re.compile(r"^import\s+\{[^}]+\}\s+from\s+['\"]([^'\"]+)['\"];?\s*$", re.MULTILINE)


def bundle(entry):
    pieces, visited, active = [], set(), set()
    def visit(path):
        path = path.resolve()
        if HERE / 'src' not in path.parents:
            raise ValueError(f'Import outside src/: {path}')
        if path in active:
            raise ValueError(f'Circular import: {path}')
        if path in visited:
            return
        active.add(path)
        source = path.read_text(encoding='utf-8')
        for match in IMPORT.finditer(source):
            if not match[1].startswith('.'):
                raise ValueError(f'Only relative imports are supported: {match[1]}')
            visit(path.parent / match[1])
        source = IMPORT.sub('', source)
        source = re.sub(r'^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\b)', '', source, flags=re.MULTILINE)
        if re.search(r'^\s*(?:import|export)\b', source, flags=re.MULTILINE):
            raise ValueError(f'Unsupported module syntax: {path}')
        pieces.append(f'\n// Source: {path.relative_to(HERE)}\n{source}')
        active.remove(path); visited.add(path)
    visit(HERE / entry)
    return "// Generated by build.py. Edit src/, not this file.\n(() => {\n'use strict';\n" + '\n'.join(pieces) + '\n})();\n'


def site_files():
    return [*PAGES, *ICONS, 'sitemap.xml', 'version.json', *[str(p.relative_to(HERE)) for p in sorted((HERE / 'assets').rglob('*')) if p.is_file()]]


def boot_page(source):
    """Generate critical startup UI from one shared source for all four entry pages."""
    head = '<style>' + (HERE / 'src/shared/page-boot.css').read_text(encoding='utf-8') + '</style>\n<script>' + (HERE / 'src/shared/page-boot.js').read_text(encoding='utf-8') + '</script>'
    head += '\n<script>' + (HERE / 'src/shared/site-update.js').read_text(encoding='utf-8') + '</script>'
    body = (HERE / 'src/shared/page-boot.html').read_text(encoding='utf-8')
    for name, content in [('head',head), ('body',body)]:
        pattern = r'<!-- boot-' + name + r':start -->[\s\S]*?<!-- boot-' + name + r':end -->'
        source = re.sub(pattern, lambda _: '<!-- boot-' + name + ':start -->\n' + content + '\n<!-- boot-' + name + ':end -->', source)
    return source


def project_sidebar(source, name):
    configs = json.loads((HERE / 'src/shared/project-sidebar.json').read_text(encoding='utf-8'))
    if name not in configs: return source
    config = configs[name]
    shell = (HERE / 'src/shared/project-sidebar.html').read_text(encoding='utf-8')
    for key in ['accept', 'list_id', 'selection_actions']:
        shell = shell.replace('{{' + key + '}}', config[key])
    shell = shell.replace('{{options}}', (HERE / config['options_file']).read_text(encoding='utf-8'))
    pattern = r'<!-- project-sidebar:start -->[\s\S]*?<!-- project-sidebar:end -->'
    if len(re.findall(pattern, source)) != 1: raise ValueError('Missing shared project sidebar: ' + name)
    return re.sub(pattern, lambda _: '<!-- project-sidebar:start -->\n' + shell + '\n<!-- project-sidebar:end -->', source)


def project_config():
    config = json.loads((HERE / 'package.json').read_text(encoding='utf-8'))
    if not re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)', config['version']):
        raise ValueError('package.json version must be MAJOR.MINOR.PATCH')
    return config


def site_page(source, name, config):
    info = json.loads((HERE / 'src/shared/site-meta.json').read_text(encoding='utf-8'))[name]
    url = config['homepage'] + ('' if name == 'index.html' else name)
    esc = lambda value: html.escape(value, quote=True)
    metadata = '\n'.join([
        '<meta name="application-build" content="BUILD_PLACEHOLDER">',
        '<meta name="description" content="' + esc(info['description']) + '">',
        '<meta name="application-name" content="BuildingWebViewer">',
        '<meta name="application-version" content="' + config['version'] + '">',
        '<link rel="canonical" href="' + url + '">',
        '<meta property="og:type" content="website">',
        '<meta property="og:title" content="' + esc(info['title']) + '">',
        '<meta property="og:description" content="' + esc(info['description']) + '">',
        '<meta property="og:url" content="' + url + '">',
    ])
    footer = (HERE / 'src/shared/site-footer.html').read_text(encoding='utf-8')
    repo = re.sub(r'\.git$', '', config['repository']['url'])
    for key, value in {'account':config['author']['url'].rstrip('/').split('/')[-1], 'author':config['author']['url'], 'repository':repo, 'release':repo + '/releases/tag/v' + config['version'], 'version':config['version']}.items():
        footer = footer.replace('{{' + key + '}}', esc(value))
    for marker, content in [('site-meta',metadata), ('site-footer',footer)]:
        pattern = r'<!-- ' + marker + r':start -->[\s\S]*?<!-- ' + marker + r':end -->'
        if len(re.findall(pattern,source)) != 1: raise ValueError(f'Missing or repeated {marker} block: {name}')
        source = re.sub(pattern, lambda _: '<!-- ' + marker + ':start -->\n' + content + '\n<!-- ' + marker + ':end -->', source)
    return source


def sitemap(config):
    urls = [config['homepage'] + ('' if name == 'index.html' else name) for name in PAGES]
    return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join('  <url><loc>' + html.escape(url) + '</loc></url>\n' for url in urls) + '</urlset>\n'


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--site', action='store_true')
    cli.add_argument('--zip', action='store_true')
    cli.add_argument('--check', action='store_true', help='Fail if tracked bundles are stale; do not write')
    args = cli.parse_args()
    config = project_config()
    target_map = HERE / 'sitemap.xml'
    if args.check:
        if not target_map.exists() or target_map.read_text(encoding='utf-8') != sitemap(config):
            raise SystemExit('Stale sitemap; run python3 build.py')
    else: target_map.write_text(sitemap(config),encoding='utf-8')
    for name, entry in ENTRIES.items():
        target = HERE / 'assets' / 'js' / f'{name}.bundle.js'
        output = bundle(entry)
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != output:
                raise SystemExit(f'Stale bundle: {target.relative_to(HERE)}; run python3 build.py')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(output, encoding='utf-8')
        print(f'{"Checked" if args.check else "Built"} {target.relative_to(HERE)}')
    # Git normalizes text on commit; reject different shipped bytes before fingerprinting/packaging.
    for name in site_files():
        path = HERE / name
        if path.suffix in {'.html', '.js', '.css', '.json', '.svg', '.xml', '.txt', '.md'} and b'\r\n' in path.read_bytes():
            raise SystemExit('Normalize shipped text to LF before building: ' + name)
    rendered_pages = {}
    for name in PAGES:
        path = HERE / name
        source = path.read_text(encoding='utf-8')
        output = site_page(project_sidebar(boot_page(source), name), name, config)
        def asset_version(match):
            name = match[2]
            digest = hashlib.sha256((HERE / name).read_bytes()).hexdigest()[:12]
            return match[1] + name + '?v=' + digest + match[3]
        output = re.sub(r'<script defer src=([\"\'])(assets/js/[^\"\']+)([\"\'])></script>', r'<script data-viewer-src=\1\2\3></script>', output)
        output = re.sub(r'(\b(?:src|href)=[\"\'])(assets/[^\"\'?]+|favicon\.svg|favicon\.ico|favicon-32\.png|apple-touch-icon\.png)(?:\?[^\"\']*)?([\"\'])', asset_version, output)
        rendered_pages[name] = output
    # Hash complete generated pages and every shipped asset, including icons.
    fingerprint = hashlib.sha256()
    for name in sorted(set(site_files()) - set(PAGES) - {'version.json'}):
        fingerprint.update(name.encode() + b'\0' + (HERE / name).read_bytes())
    for name, output in rendered_pages.items():
        fingerprint.update(name.encode() + b'\0' + output.encode())
    build_id = fingerprint.hexdigest()[:16]
    for name, output in rendered_pages.items():
        output = output.replace('BUILD_PLACEHOLDER', build_id)
        path = HERE / name
        if args.check:
            if path.read_text(encoding='utf-8') != output: raise SystemExit(f'Stale startup shell: {name}; run python3 build.py')
        else: path.write_text(output, encoding='utf-8')
    manifest = json.dumps({'version': config['version'], 'build': build_id}, indent=2) + '\n'
    if args.check:
        if not (HERE / 'version.json').exists() or (HERE / 'version.json').read_text() != manifest: raise SystemExit('Stale version.json; run python3 build.py')
    else: (HERE / 'version.json').write_text(manifest, encoding='utf-8')
    if args.site:
        target = HERE / '_site'
        if target.is_symlink():
            raise ValueError('Refusing to replace a symlink at _site')
        if target.exists(): shutil.rmtree(target)
        target.mkdir()
        for name in site_files():
            (target / name).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(HERE / name, target / name)
        (target / '.nojekyll').touch()
        print(f'Static website: {target}')
    if args.zip:
        files = site_files() + ['build.py','server.py','start.sh','package.json','README.md','README.en.md','CHANGELOG.md','AGENTS.md','.gitignore','.gitattributes']
        for folder in ['src','tests','scripts','docs','.github']:
            files.extend(str(f.relative_to(HERE)) for f in sorted((HERE / folder).rglob('*')) if f.is_file())
        for f in sorted((HERE / 'mobile').rglob('*')):
            rel = f.relative_to(HERE / 'mobile')
            if not f.is_file() or any(part in {'node_modules','web','.gradle','build','.idea','capacitor-cordova-android-plugins','assets'} for part in rel.parts): continue
            if f.name in {'local.properties'} or f.suffix in {'.apk','.jks','.keystore','.log'}: continue
            files.append(str(f.relative_to(HERE)))
        target = HERE / 'dist' / ('BuildingWebViewer-v' + config['version'] + '.zip')
        target.parent.mkdir(exist_ok=True)
        with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED,compresslevel=9) as archive:
            for name in sorted(set(files)):
                # Stable timestamps and modes make the download reproducible from its tag.
                info = zipfile.ZipInfo('BuildingWebViewer/' + name, date_time=(2020,1,1,0,0,0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (0o100755 if name in {'start.sh','mobile/android/gradlew'} else 0o100644) << 16
                archive.writestr(info, (HERE / name).read_bytes())
        digest = hashlib.sha256(target.read_bytes()).hexdigest()
        (target.parent / 'SHA256SUMS.txt').write_text(digest + '  ' + target.name + '\n',encoding='utf-8')
        shutil.copy2(target,target.parent / 'BuildingWebViewer.zip')
        print(f'Package: {target} ({target.stat().st_size:,} bytes; no datasets)')


if __name__ == '__main__': main()
