import assert from 'node:assert/strict';
import {wirePreference,wireEntryFiles,combineWireframes,adjacentWireEntry,wireNavigationDirection,normalizeWirePreferences} from '../src/cloud/wire-selection.js';
import {parseWireOBJ} from '../src/cloud/point-io.js';
const file=name=>({name});
const first={wires:[file('raw.obj'),file('refined.obj')],clouds:[file('pc.xyz')]};
const reordered={wires:[file('REFINED.OBJ'),file('raw.obj'),file('extra.obj')],clouds:[file('other.xyz'),file('PC.XYZ')]};
const prefs={wires:[wirePreference(first.wires,'1'),null,null],cloud:wirePreference(first.clouds,'0')};
assert.equal(wireEntryFiles(reordered,prefs,2).wires[0],reordered.wires[0]);
assert.equal(wireEntryFiles(reordered,prefs,2).cloud,reordered.clouds[1]);
const fewer={wires:[file('different.obj')],clouds:[]};
assert.equal(wireEntryFiles(fewer,prefs,3).wires[0],fewer.wires[0]);
assert.deepEqual(wireEntryFiles(fewer,prefs,3).wires.slice(1),[null,null]);
assert.equal(wireEntryFiles(first,{wires:[{none:true}],cloud:{none:true}}).wires[0],null);
assert.equal(wireEntryFiles(first,{wires:[null],cloud:{none:true}}).cloud,null);
assert.deepEqual(normalizeWirePreferences({wires:[{name:'bad',index:-2}],count:999,compare:'yes'}),{wires:[null,null,null],cloud:null,count:2,compare:false});
console.log('PASS variants match filenames despite reordered files, fall back safely, and retain intentional None');
const a=parseWireOBJ('v 1000000 0 0\nv 1000001 0 0\nl 1 2');
const b=parseWireOBJ('v -20 2 3\nv -19 2 3\nl 1 2');
const combined=combineWireframes([a,null,b]);
assert.deepEqual(combined.edges,[[0,1],[2,3]]);
assert.deepEqual(combined.vertices,[...a.vertices,...b.vertices]);
assert.deepEqual(combined.bounds,[[-20,0,0],[1000001,2,3]]);
assert.equal(combineWireframes([a]),a);assert.equal(combineWireframes([]),null);
assert.deepEqual(a.edges,[[0,1]]);assert.equal(a.vertices.length,2);
console.log('PASS overlays preserve large original coordinates, disconnected edge topology and source data');
const ids=['10','2','1'].map(id=>({id}));
assert.equal(adjacentWireEntry(ids,ids[2],1),ids[1]);
assert.equal(adjacentWireEntry(ids,ids[0],1),ids[0]);
assert.equal(adjacentWireEntry(ids.filter(e=>e.id!=='2'),ids[2],1),ids[0]);
assert.equal(adjacentWireEntry([],null,1),null);
assert.equal(wireNavigationDirection({key:'ArrowRight'}),1);
assert.equal(wireNavigationDirection({key:'['}),-1);
for(const state of [{multiple:true},{flying:true}])assert.equal(wireNavigationDirection({key:'ArrowRight'},state),0);
for(const event of [{key:'ArrowRight',ctrlKey:true},{key:'ArrowLeft',repeat:true},{key:']',target:{closest:()=>({})}}])assert.equal(wireNavigationDirection(event),0);
console.log('PASS natural/filter-aware ID navigation respects endpoints, editing controls and fly mode');
